    private void btnBuscarIdEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarIdEliminarActionPerformed
        // TODO add your handling code here:
        int datoid = Integer.parseInt(txtEliminarPorID.getText());
        String resultadoid = null ; 
        for(i=0 ; i< Data.contador ; i++) {
            if(Data.IDpersonaje[i]== datoid){
                resultadoid = "¿DESEA ELIMINAR ESTE PERSONAJE?" + "\n"
                + "Nombre: " + Data.NombresPersonajes[i] + "\n"        
                + "ID: " + Data.IDpersonaje[i] + "\n"
                + "Arma: " + Data.NombresArmas[i] + "\n"
                + "Puntos de vida: " + Data.PuntosVida[i] + "\n"
                + "Ataque del personaje: " + Data.NivelAtaque[i] + "\n"
                + "Velocidad del personaje: " + Data.Velocidad[i] + "\n"
                + "Agilidad del personaje: " + Data.Agilidad[i] + "\n"
                + "Defensa del personaje: " + Data.Defensa[i] + "\n" ;
            }
            posicion = i ;
        }
        
        txtResultadoBEliminar.setText(resultadoid);
    }//GEN-LAST:event_btnBuscarIdEliminarActionPerformed

