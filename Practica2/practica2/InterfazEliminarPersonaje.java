    private void btnConfirmarEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarEliminarActionPerformed
        // TODO add your handling code here:
       for(int j = posicion ; j < Data.contador - 1; j++){
           Data.NombresPersonajes[j] = Data.NombresPersonajes[j+1] ;
           Data.NombresArmas[j] = Data.NombresArmas[j+1] ;
           Data.PuntosVida[j] = Data.PuntosVida[j+1] ;
           Data.NivelAtaque[j] = Data.NivelAtaque[j+1] ;
           Data.Velocidad[j] = Data.Velocidad[j+1] ;
           Data.Agilidad[j] = Data.Agilidad[j+1] ;
           Data.Defensa[j] = Data.Defensa[j+1] ;
           Data.IDpersonaje[j] = Data.IDpersonaje[j+1] ;
        }
       
        Data.NombresPersonajes[Data.contador-1] = null ;
           Data.NombresArmas[Data.contador-1] = null ;
           Data.PuntosVida[Data.contador-1] = 0 ;
           Data.NivelAtaque[Data.contador -1] = 0 ;
           Data.Velocidad[Data.contador-1] = 0 ;
           Data.Agilidad[Data.contador-1] = 0 ;
           Data.Defensa[Data.contador-1] = 0;
           Data.IDpersonaje[Data.contador-1] =0;
           
           Data.contador-- ;
           Data.contadorId-- ;
           JOptionPane.showMessageDialog(this, "Personaje eliminado correctamente");
           
           im.setVisible(true) ;
           this.setVisible(false) ;
    }//GEN-LAST:event_btnConfirmarEliminarActionPerformed

